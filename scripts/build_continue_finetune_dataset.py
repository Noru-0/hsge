#!/usr/bin/env python3
"""Build the increment dataset for continue-finetuning checkpoint-536.

Scope: ONLY the genuinely new data collected after checkpoint-536 was
trained -- reddit (wa_run_21/22) and shopping_admin (wa_run_21/22), from
`training_data_v2/train_wa_run_{21,22}_{reddit,shopping_admin}.jsonl` (already
goal-deduped, no val leakage; see `training_data_v2/`). Plus a small replay
sample of shopping/gitlab from the ORIGINAL `training_data/` (what
checkpoint-536 was actually trained on) so a continue-finetune pass that only
sees reddit/shopping_admin doesn't catastrophically forget those two domains.

Replay ratio: ~15% of the final train set (and same ratio for val), split
evenly between shopping and gitlab, sampled by whole trajectory (never a
partial trajectory) with a fixed seed for reproducibility.

Output:
  - training_data_continue_v1/{train,val}.jsonl -- full metadata, repo-root
    convention like training_data/ and training_data_v2/.
  - training/data/continue_v1/{train,val}.jsonl + dataset_info.json --
    LLaMA-Factory-ready (messages-only), what
    training/qwen35_9b_lora_continue_v1.yaml actually reads. Gitignored
    (training/data/*/), regenerated by this script every run.

Usage:
    python scripts/build_continue_finetune_dataset.py
"""
from __future__ import annotations

import json
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
V2 = ROOT / "training_data_v2"
V1 = ROOT / "training_data"
OUT = ROOT / "training_data_continue_v1"
LF_OUT = ROOT / "training" / "data" / "continue_v1"
SEED = 42
REPLAY_RATIO = 0.15  # of the final combined set, split evenly shopping/gitlab

INCREMENT_TRAIN_FILES = [
    "train_wa_run_21_reddit.jsonl",
    "train_wa_run_22_reddit.jsonl",
    "train_wa_run_21_shopping_admin.jsonl",
    "train_wa_run_22_shopping_admin.jsonl",
]
INCREMENT_RUNS = {
    "wa_run_21_reddit": "reddit",
    "wa_run_22_reddit": "reddit",
    "wa_run_21_shopping_admin": "shopping_admin",
    "wa_run_22_shopping_admin": "shopping_admin",
}
REPLAY_SITES = ["shopping", "gitlab"]

_LF_COLUMNS = {
    "file_name": None,  # filled in per split below
    "formatting": "sharegpt",
    "columns": {"messages": "messages"},
    "tags": {
        "role_tag": "role",
        "content_tag": "content",
        "user_tag": "user",
        "assistant_tag": "assistant",
        "system_tag": "system",
    },
}


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.open() if line.strip()]


def write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")


def sample_trajectories_by_site(
    rows: list[dict], site: str, target_rows: int, rng: random.Random
) -> list[dict]:
    """Randomly pick whole trajectories of `site` until >= target_rows steps."""
    by_traj: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        if r.get("site") == site:
            by_traj[r["trajectory_id"]].append(r)
    traj_ids = list(by_traj.keys())
    rng.shuffle(traj_ids)
    picked: list[dict] = []
    for tid in traj_ids:
        if len(picked) >= target_rows:
            break
        picked.extend(sorted(by_traj[tid], key=lambda r: r["step_index"]))
    return picked


def main() -> None:
    rng = random.Random(SEED)
    OUT.mkdir(exist_ok=True)

    # 1. Increment: new reddit + shopping_admin data (run 21/22), untouched.
    increment_train: list[dict] = []
    for fname in INCREMENT_TRAIN_FILES:
        run = fname.removeprefix("train_").removesuffix(".jsonl")
        site = INCREMENT_RUNS[run]
        for row in load_jsonl(V2 / fname):
            row = dict(row)
            row["site"] = site
            row["run"] = run
            increment_train.append(row)

    v2_val = load_jsonl(V2 / "val.jsonl")
    increment_val = [r for r in v2_val if r.get("run") in INCREMENT_RUNS]

    # 2. Replay: shopping + gitlab from the ORIGINAL checkpoint-536 dataset.
    v1_train = load_jsonl(V1 / "train.jsonl")
    v1_val = load_jsonl(V1 / "val.jsonl")

    n_inc_train = len(increment_train)
    n_inc_val = len(increment_val)
    replay_train_target_total = round(REPLAY_RATIO * n_inc_train / (1 - REPLAY_RATIO))
    replay_val_target_total = round(REPLAY_RATIO * n_inc_val / (1 - REPLAY_RATIO))
    per_site_train_target = replay_train_target_total // 2
    per_site_val_target = replay_val_target_total // 2

    replay_train: list[dict] = []
    replay_val: list[dict] = []
    for site in REPLAY_SITES:
        replay_train.extend(
            sample_trajectories_by_site(v1_train, site, per_site_train_target, rng)
        )
        replay_val.extend(
            sample_trajectories_by_site(v1_val, site, per_site_val_target, rng)
        )
    for row in replay_train:
        row["run"] = f"replay_{row['site']}_v20"
    for row in replay_val:
        row["run"] = f"replay_{row['site']}_v20"

    # 3. Combine, sort by difficulty ascending (curriculum convention, stable
    #    so trajectory step order is preserved within a difficulty band).
    train = increment_train + replay_train
    val = increment_val + replay_val
    train.sort(key=lambda r: r["difficulty"])
    val.sort(key=lambda r: r["difficulty"])

    write_jsonl(OUT / "train.jsonl", train)
    write_jsonl(OUT / "val.jsonl", val)

    # 4. Stage the LLaMA-Factory-ready (messages-only) copy + dataset_info.json.
    LF_OUT.mkdir(parents=True, exist_ok=True)
    write_jsonl(LF_OUT / "train.jsonl", [{"messages": r["messages"]} for r in train])
    write_jsonl(LF_OUT / "val.jsonl", [{"messages": r["messages"]} for r in val])
    dataset_info = {}
    for split, name in (("train", "hsge_continue_v1_train"), ("val", "hsge_continue_v1_val")):
        entry = json.loads(json.dumps(_LF_COLUMNS))  # deep copy
        entry["file_name"] = f"{split}.jsonl"
        dataset_info[name] = entry
    (LF_OUT / "dataset_info.json").write_text(json.dumps(dataset_info, indent=2) + "\n")

    print(f"increment train: {n_inc_train} (reddit+shopping_admin, wa_run_21/22)")
    print(f"replay train:    {len(replay_train)} (shopping+gitlab, from training_data/)")
    print(f"TOTAL train:     {len(train)}  -> {OUT / 'train.jsonl'}")
    print()
    print(f"increment val:   {n_inc_val}")
    print(f"replay val:      {len(replay_val)}")
    print(f"TOTAL val:       {len(val)}  -> {OUT / 'val.jsonl'}")


if __name__ == "__main__":
    main()
